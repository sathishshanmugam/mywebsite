function slugifyProductName(name){

  return name
    .toLowerCase()
    .trim()
    .replace(/&/g, "and")
    .replace(/[^a-z0-9]+/g, "_")
    .replace(/^-+|-+$/g, "");

}
async function loadOutletAvailability(outletId){

  availableProductIds = new Set();

  if(!outletId){
    renderMenu();
    return;
  }

  try{

    const snapshot = await db
      .collection("outlet_products")
      .where("outletId", "==", outletId)
      .where("available", "==", true)
      .get();

    snapshot.forEach(doc => {

      const data = doc.data();

      if(data.productId){
        availableProductIds.add(data.productId);
      }

    });

    console.log(
      `🔥 ${outletId}: ${availableProductIds.size} products ON`
    );

    renderMenu();

  }catch(error){

    console.error(
      "❌ Failed to load outlet availability:",
      error
    );

    alert(
      "Unable to load the selected outlet menu. Please try again."
    );

  }

}
async function selectOutlet(outletId){

  try{

    /*
      If customer already has items in the cart
      and tries to change outlet, warn them first.
    */
    if(
      selectedOutletId &&
      selectedOutletId !== outletId &&
      cart.length > 0
    ){

      const changeOutlet =
        confirm(
          "Changing the outlet will clear your current cart. Do you want to continue?"
        );

      if(!changeOutlet){
        return;
      }

      cart = [];

      saveCart();

      renderCart();

    }


    const outletDoc = await db
      .collection("outlets")
      .doc(outletId)
      .get();


    if(!outletDoc.exists){

      alert("Outlet information could not be found.");

      return;

    }


    const outlet = outletDoc.data();


    if(outlet.active !== true){

      alert("This outlet is currently unavailable.");

      return;

    }


    /*
      Store selected outlet information.
    */
    selectedOutletId =
      outletId;

    selectedOutletName =
      outlet.name || outletId;

    selectedOutletWhatsapp =
      outlet.whatsapp || "";


    /*
      New outlet means customer must choose
      Dine-In or Pick-Up again.
    */
    selectedOrderType = "";


    /*
      Load product availability for this outlet.
    */
    await loadOutletAvailability(
      outletId
    );


    /*
      Update the selection bar above the menu.
    */
    renderOrderSelectionBar();


    /*
      Re-render menu so the buttons update.
    */
    renderMenu();


    /*
      Now ask customer for:
      Dine-In / Pick-Up
    */
    showOrderTypeStep();


    const orderBar = $("orderSelectionBar");

if(orderBar){
  orderBar.scrollIntoView({
    behavior: "smooth",
    block: "start"
  });
}

console.log(
  `📍 Selected outlet: ${selectedOutletName}`
);


  }catch(error){

    console.error(
      "❌ Outlet selection error:",
      error
    );

    alert(
      "Unable to select this outlet. Please try again."
    );

  }

}
