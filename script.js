function uniqueCategories(){
  return [...new Set(MENU.map(x => x.category).filter(Boolean))];
}

function emojiFor(item){
  const c = item.category;
  if (categoryIcons[c]) return categoryIcons[c];
  const n = item.name.toLowerCase();
  if(n.includes("chicken")) return "🍗";
  if(n.includes("mushroom")) return "🍄";
  if(n.includes("paneer")) return "🧀";
  if(n.includes("egg")) return "🥚";
  if(n.includes("coffee")) return "☕";
  if(n.includes("shake")) return "🥤";
  return "🍽️";
}

function setupCategories(){
  const cats = uniqueCategories();
  const strip = $("categoryStrip");
  const filter = $("categoryFilter");
  strip.innerHTML = `<button class="cat-pill active" data-cat="All"><span class="cat-icon">✨</span><span>All Menu</span></button>` +
    cats.map(c => `<button class="cat-pill" data-cat="${escapeHtml(c)}"><span class="cat-icon">${categoryIcons[c] || "🍽️"}</span><span>${escapeHtml(c)}</span></button>`).join("");
  filter.innerHTML = `<option value="All">All categories</option>` + cats.map(c => `<option>${escapeHtml(c)}</option>`).join("");

  strip.querySelectorAll(".cat-pill").forEach(btn => btn.addEventListener("click", () => {
    selectedCategory = btn.dataset.cat;
    filter.value = selectedCategory;
    strip.querySelectorAll(".cat-pill").forEach(b => b.classList.toggle("active", b === btn));
    renderMenu();
  }));
  filter.addEventListener("change", () => {
    selectedCategory = filter.value;
    strip.querySelectorAll(".cat-pill").forEach(b => b.classList.toggle("active", b.dataset.cat === selectedCategory));
    renderMenu();
  });
  $("menuSearch").addEventListener("input", renderMenu);
}

function renderMenu(){

  const q = $("menuSearch").value.trim().toLowerCase();

  let list = MENU.filter(item => {

    const categoryMatch =
      selectedCategory === "All" ||
      item.category === selectedCategory;

    const searchMatch =
      !q ||
      item.name.toLowerCase().includes(q) ||
      item.category.toLowerCase().includes(q);

    return categoryMatch && searchMatch;
  });


  $("menuGrid").innerHTML = list.length
    ? list.map(item => {

        const productId =
          slugifyProductName(item.name);

        const available =
        !!selectedOutletId &&
        availableProductIds.has(productId);

        return cardHtml(item, available);

      }).join("")

    : `
      <div class="empty-cart" style="grid-column:1/-1">
        No dishes found. Try another search. 🍽️
      </div>
    `;


  $("menuGrid")
   .querySelectorAll(".add-btn:not(:disabled)")
    .forEach(btn => {

      btn.addEventListener(
        "click",
        () => addToCart(Number(btn.dataset.index))
      );

    });

}

function cardHtml(item, available){

  const index = MENU.indexOf(item);

  const type = item.type || "veg";

  const badge =
    type === "non-veg"
      ? "NON-VEG"
      : type === "egg"
        ? "EGG"
        : "VEG";

  const price =
    Number(item.price) > 0
      ? money(item.price)
      : "On selection";


  let buttonHtml = "";

  /*
    Customer can add items only after BOTH:
    1. Outlet is selected
    2. Order type is selected
  */
  if(!selectedOutletId || !selectedOrderType){

    buttonHtml = `
      <button
        class="add-btn"
        type="button"
        disabled
      >
        SELECT OUTLET &amp; ORDER TYPE
      </button>
    `;

  /*
    Outlet is selected and order type is selected,
    but this particular product is OFF in Firebase.
  */
  }else if(!available){

    buttonHtml = `
      <button
        class="add-btn"
        type="button"
        disabled
      >
        SOLD OUT
      </button>
    `;

  /*
    Outlet + order type selected and product is available.
  */
  }else{

    buttonHtml = `
      <button
        class="add-btn"
        type="button"
        data-index="${index}"
      >
        ADD +
      </button>
    `;

  }


  return `<article class="menu-card">

    <span class="badge ${type}">${badge}</span>

    <div class="food-image">
      ${
        item.image
          ? `<img src="${escapeHtml(item.image)}" alt="${escapeHtml(item.name)}">`
          : emojiFor(item)
      }
    </div>

    <div class="menu-card-body">

      <h4>${escapeHtml(item.name)}</h4>

      <div class="menu-desc">
        ${escapeHtml(item.description || "Freshly prepared at Crunchery's.")}
      </div>

      <div class="menu-bottom">

        <span class="price">
          ${price}
        </span>

        ${buttonHtml}

      </div>

    </div>

  </article>`;

}
